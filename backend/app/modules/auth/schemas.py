from uuid import UUID

from pydantic import BaseModel, Field, field_validator

from app.modules.auth.phone import normalize_phone


class _PhoneBody(BaseModel):
    phone: str = Field(max_length=32, examples=["0771234567"])

    @field_validator("phone")
    @classmethod
    def _normalize(cls, v: str) -> str:
        return normalize_phone(v)


class OtpRequest(_PhoneBody):
    pass


class OtpRequested(BaseModel):
    expires_in: int        # seconds until the code expires
    resend_after: int      # seconds before another code may be requested


class OtpVerify(_PhoneBody):
    code: str = Field(pattern=r"^\d{6}$")
    # Generated by the client once and kept in local storage.
    device_id: str = Field(min_length=8, max_length=128)
    # Required only the first time a phone number signs up.
    full_name: str | None = Field(default=None, min_length=1, max_length=120)


class RefreshRequest(BaseModel):
    refresh_token: str = Field(min_length=20, max_length=200)


class TokenPair(BaseModel):
    access_token: str
    refresh_token: str
    token_type: str = "bearer"
    expires_in: int        # access token lifetime, seconds


class Me(BaseModel):
    user_id: UUID
    member_id: UUID
    full_name: str
    phone: str | None
    role: str
    preferred_language: str
